#!/usr/bin/env python3
"""Generate common native expectations for byte candidates and zero-value reader layouts."""
import json
import os
import struct
import subprocess
from upstream import ROOT, LOCK, fetch


def audit():
    source = fetch()
    binary = ROOT / '.cache/probes/candidate_probe'
    binary.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run([os.environ.get('CXX', 'c++'), '-std=c++17', '-O2', '-DOpencc_BUILT_AS_STATIC', '-I', str(source / 'src'),
                    str(ROOT / 'tools/oracle/candidate_probe.cpp'), str(ROOT / '.cache/oracle/src/libopencc.a'),
                    str(ROOT / '.cache/oracle/deps/marisa-0.3.1/libmarisa.a'), '-o', str(binary)], check=True)
    target = ROOT / '.cache/conformance/candidates'
    target.mkdir(parents=True, exist_ok=True)
    resources = {'first.txt': '里\t里 裏\n面\t麵 面\na\tx\nb\ty z\n里字\t⿱艹里\n',
                 'second.txt': '裏\t裡\n麵\t面\ny\tm n\n里\t裏\n',
                 'long.txt': '里面\t裏面\nab\tQ R\n'}
    for name, text in resources.items(): (target / name).write_text(text)
    text_dict = lambda name: {'type': 'text', 'file': name}
    configs = {
        'single': {'conversion_chain': [{'dict': text_dict('first.txt')}]},
        'chained': {'conversion_chain': [{'dict': text_dict(name)} for name in ['first.txt', 'second.txt']]},
        'partial': {'conversion_chain': [{'dict': text_dict(name)} for name in ['long.txt', 'second.txt']]},
        'normalized': {'normalization': [{'dict': {'type': 'inline', 'entries': {'里': '里'}}}],
                       'conversion_chain': [{'dict': text_dict(name)} for name in ['first.txt', 'second.txt']]},
        'short_circuit': {'conversion_chain': [{'dict': {'type': 'group', 'dicts': [text_dict('first.txt'), text_dict('long.txt')]}}]},
        'union': {'conversion_chain': [{'dict': {'type': 'group', 'match_policy': 'union', 'dicts': [text_dict('first.txt'), text_dict('long.txt')]}}]},
        'empty': {'conversion_chain': []},
        'nul': {'conversion_chain': [{'dict': {'type': 'inline', 'entries': {'a': 'A\0tail', 'b\0tail': 'B'}}}]},
    }
    inputs = [text.encode() for text in ['', '里', '里面', '里字', '面', '里', '国', 'a', 'b', 'ab', 'aba', 'a\0b', '⿱艹里', '𠀀里']]
    inputs += [bytes.fromhex(value) for value in ['e987', 'f880808080', 'fc8080808080', 'c080', 'e44141', '80', 'ff']]
    inputs += ['里'.encode() + bytes.fromhex('e987')]
    inputs += [bytes([lead]) for lead in range(256)]
    rows = []
    for name, config in configs.items():
        path = target / (name + '.json'); path.write_text(json.dumps(config, ensure_ascii=False))
        result = subprocess.run([str(binary), 'candidates', str(path), str(target)], input=''.join(data.hex() + '\n' for data in inputs),
                                capture_output=True, text=True, check=True, timeout=30)
        results = result.stdout.splitlines(); assert len(results) == len(inputs)
        rows += [name + '|' + data.hex() + '|' + outcome for data, outcome in zip(inputs, results)]
    def binary_dict(width, entries):
        field = lambda number: int(number).to_bytes(width, 'little')
        keys = bytearray(); values = bytearray(); offsets = bytearray()
        for key, candidates in entries:
            offsets += field(len(candidates)) + field(len(keys)); keys += key.encode() + b'\0'
            for candidate in candidates:
                offsets += field(len(values)); values += candidate.encode() + b'\0'
        return field(len(entries)) + field(len(keys)) + keys + field(len(values)) + values + offsets
    def value_dict(entries):
        values = bytearray(); lengths = bytearray()
        for candidates in entries:
            lengths += struct.pack('<H', len(candidates))
            for value in candidates:
                encoded = value.encode() + b'\0'; values += encoded; lengths += struct.pack('<H', len(encoded))
        return struct.pack('<II', len(entries), len(values)) + values + lengths
    dictionary_cases = [('binary', binary_dict(width, entries)) for width in [4, 8]
                        for entries in [[('hi', [])], [('hi', []), ('z', ['Z'])], [('hi', ['H']), ('z', [])]]]
    dictionary_cases += [('values', value_dict(entries)) for entries in [[[]], [[], ['Z']], [['H'], []]]]
    dictionary_rows = []
    for operation, image in dictionary_cases:
        outcome = subprocess.run([str(binary), operation], input=image.hex() + '\n', capture_output=True, text=True, check=True).stdout.strip()
        assert outcome.startswith('OK'), (operation, outcome)
        dictionary_rows.append(operation + '|' + image.hex() + '|' + outcome)
    fixture = ROOT / 'opencc-core/src/commonTest/kotlin/io/github/opencckmp/NativeCandidateCases.kt'
    output = '// Generated by tools/audit_candidates.py from pinned OpenCC ver.1.4.2; test data only.\npackage io.github.opencckmp\n\n'
    def block(text): return '"""' + text + '"""'
    output += 'internal val nativeCandidateResources = mapOf(\n' + ',\n'.join('    "' + name + '" to ' + block(text) for name, text in resources.items()) + '\n)\n'
    output += 'internal val nativeCandidateConfigs = mapOf(\n' + ',\n'.join('    "' + name + '" to ' + block(json.dumps(config, ensure_ascii=False)) for name, config in configs.items()) + '\n)\n'
    output += 'internal val nativeCandidateCases = ' + block('\n' + '\n'.join(rows) + '\n') + '.trim().lines()\n'
    output += 'internal val nativeZeroValueCases = ' + block('\n' + '\n'.join(dictionary_rows) + '\n') + '.trim().lines()\n'
    fixture.write_text(output)
    report = {'upstream': LOCK, 'candidate_cases': len(rows), 'zero_value_reader_cases': len(dictionary_rows), 'configurations': list(configs)}
    (ROOT / 'docs/candidate-contract-audit.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__': audit()

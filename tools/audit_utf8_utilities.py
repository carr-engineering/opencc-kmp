#!/usr/bin/env python3
"""Regenerate common-test golden cases from pinned native UTF8Util operations."""
import hashlib
import json
import os
import subprocess
from upstream import ROOT, LOCK, fetch


def audit():
    source = fetch()
    probe = ROOT / 'tools/oracle/utf8_util_probe.cpp'
    binary = ROOT / '.cache/probes/utf8_util_probe'
    binary.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run([os.environ.get('CXX', 'c++'), '-std=c++17', '-O2', '-DOpencc_BUILT_AS_STATIC',
                    '-I', str(source / 'src'), str(probe), str(ROOT / '.cache/oracle/src/libopencc.a'),
                    str(ROOT / '.cache/oracle/deps/marisa-0.3.1/libmarisa.a'), '-o', str(binary)], check=True)
    cases = [('width', 0, bytes([lead])) for lead in range(256)]
    inputs = [text.encode() for text in ['', 'A東𠍀', '東\ufe0f', '東\U000e0100', '⿰東𠍀', '⿲東木水', '⿾東', '⿰⿰東木水',
              '⿰', '⿰東', '⿰' * 15 + '東' * 16, '⿰' * 16 + '東' * 17, 'A\0B']]
    inputs += [bytes.fromhex(value) for value in ['80', 'ff', 'c080', 'e04142', 'e00080', 'e2', 'e261', 'f880808080',
              'fc8080808080', '80efb88f', 'efb8', 'c041efb88f', 'e2bfb04142', 'e2bfb0e2']]
    for data in inputs:
        for end in range(len(data) + 1):
            part = data[:end]
            cases += [(op, 0, part) for op in ['length', 'selector', 'ids', 'incomplete']]
            cases += [('truncate', budget, part) for budget in sorted({0, 1, 3, 4, 5, len(part), len(part) + 1})]
    wire = ''.join(f'{op}\t{arg}\t{data.hex()}\n' for op, arg, data in cases)
    result = subprocess.run([str(binary)], input=wire, text=True, capture_output=True, check=True, timeout=30)
    outcomes = result.stdout.splitlines()
    assert len(outcomes) == len(cases)
    rows = [f'{op}|{arg}|{data.hex()}|{outcome}' for (op, arg, data), outcome in zip(cases, outcomes)]
    fixture = ROOT / 'opencc-core/src/commonTest/kotlin/io/github/opencckmp/NativeUtf8UtilityCases.kt'
    fixture.write_text('// Generated by tools/audit_utf8_utilities.py from pinned OpenCC ver.1.4.2; test data only.\n'
                       'package io.github.opencckmp\n\ninternal val nativeUtf8UtilityCases = """\n' + '\n'.join(rows) + '\n""".trim().lines()\n')
    report = {'upstream': LOCK, 'cases': len(cases), 'fixture_sha256': hashlib.sha256(fixture.read_bytes()).hexdigest(),
              'operations': ['NextCharLengthNoException', 'Length', 'TruncateUTF8', 'ContainsVariationSelector',
                             'NextIdeographicDescriptionSequenceLength', 'IsIncompleteIdeographicDescriptionSequencePrefix'],
              'scope': 'Native-generated expectations checked by common tests. No C++ pointer/ownership ABI equivalence asserted.'}
    (ROOT / 'docs/utf8-utility-audit.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__': audit()

#!/usr/bin/env python3
"""Generate native skip-distance expectations for text, grouped, Darts and MARISA dictionaries."""
import json
import os
import subprocess
from upstream import ROOT, LOCK, fetch


def audit():
    source = fetch(); target = ROOT / '.cache/conformance/prefix-scan'; target.mkdir(parents=True, exist_ok=True)
    binary = ROOT / '.cache/probes/prefix_scan_probe'
    subprocess.run([os.environ.get('CXX', 'c++'), '-std=c++17', '-O2', '-DOpencc_BUILT_AS_STATIC', '-I', str(source / 'src'),
                    str(ROOT / 'tools/oracle/prefix_scan_probe.cpp'), str(ROOT / '.cache/oracle/src/libopencc.a'),
                    str(ROOT / '.cache/oracle/deps/marisa-0.3.1/libmarisa.a'), '-o', str(binary)], check=True)
    resources = {'mixed.txt': 'ab\tX\nz\tZ\n太后\t太后\n头发\t頭髮\n干燥\t乾燥\n清華\tTsinghua\n𠀀\t甲\n',
                 'chinese.txt': '太后\t太后\n头发\t頭髮\n干燥\t乾燥\n',
                 'base.txt': 'BYVoid\tbyv\nzigzagzig\tzag\n積羽沉舟\t羣輕折軸\n清\tTsing\n清華\tTsinghua\n清華大學\tTsinghuaUniversity\n', 'empty.txt': ''}
    for name, text in resources.items(): (target / name).write_text(text)
    native_dict_tool = ROOT / '.cache/oracle/src/tools/opencc_dict'
    for fmt in ['ocd', 'ocd2']:
        subprocess.run([str(native_dict_tool), '-i', str(target / 'mixed.txt'), '-o', str(target / ('mixed.' + fmt)), '-f', 'text', '-t', fmt], check=True, capture_output=True)
    subprocess.run([str(native_dict_tool), '-i', str(target / 'base.txt'), '-o', str(target / 'base.ocd2'), '-f', 'text', '-t', 'ocd2'], check=True, capture_output=True)
    text = lambda name: {'type': 'text', 'file': name}
    dictionaries = {'mixed': text('mixed.txt'), 'chinese': text('chinese.txt'), 'empty': text('empty.txt'),
                    'group': {'type': 'group', 'dicts': [text('mixed.txt'), text('chinese.txt')]},
                    'union': {'type': 'group', 'match_policy': 'union', 'dicts': [text('mixed.txt'), text('chinese.txt')]},
                    'darts': {'type': 'ocd', 'file': 'mixed.ocd'}, 'marisa': {'type': 'ocd2', 'file': 'mixed.ocd2'},
                    'base_marisa': {'type': 'ocd2', 'file': 'base.ocd2'},
                    'base_table': {'type': 'group', 'dicts': [{'type': 'ocd2', 'file': 'base.ocd2'}, text('base.txt')]}}
    configs = {name: {'conversion_chain': [{'dict': dictionary}]} for name, dictionary in dictionaries.items()}
    inputs = [value.encode() for value in ['', 'a', 'ax', 'zz', 'plain ASCII', 'hello太后', '一天干燥', '未知中文',
              '——。！太后', 'éø太后', '😀', '𠀀', 'abc\0tail', '⿰木木', '⿱艹⿰钅只', 'x' * 512]]
    inputs += [chr(point).encode() for point in range(0x2FF0, 0x3000)]
    inputs += [bytes.fromhex(hex) for hex in ['80', 'ff', 'e2', 'e261', 'e27fb0', 'c1a1', 'c080', 'e08080', 'f880808080', 'fc8080808080']]
    inputs += [b'x' + bytes([lead]) for lead in range(256)]
    inputs += ['hello太后'.encode()[:cut] for cut in range(len('hello太后'.encode()) + 1)]
    rows = []
    for name, config in configs.items():
        path = target / (name + '.json'); path.write_text(json.dumps(config, ensure_ascii=False))
        result = subprocess.run([str(binary), str(path), str(target)], input=''.join(value.hex() + '\n' for value in inputs),
                                text=True, capture_output=True, check=True, timeout=30)
        outcomes = result.stdout.splitlines(); assert len(outcomes) == len(inputs)
        rows += [name + '|' + value.hex() + '|' + outcome for value, outcome in zip(inputs, outcomes)]
    fixture = ROOT / 'opencc-core/src/commonTest/kotlin/io/github/opencckmp/NativePrefixScanCases.kt'
    block = lambda value: '"""' + value + '"""'
    output = '// Generated by tools/audit_prefix_scan.py from pinned OpenCC ver.1.4.2; test data only.\npackage io.github.opencckmp\n\n'
    output += 'internal val nativePrefixScanResources = mapOf(\n' + ',\n'.join('    "' + name + '" to ' + block(value) + '.encodeToByteArray()' for name, value in resources.items()) + ',\n'
    output += ',\n'.join('    "mixed.' + fmt + '" to ' + block((target / ('mixed.' + fmt)).read_bytes().hex()) + '.chunked(2).map { it.toInt(16).toByte() }.toByteArray()' for fmt in ['ocd', 'ocd2']) + ',\n    "base.ocd2" to ' + block((target / 'base.ocd2').read_bytes().hex()) + '.chunked(2).map { it.toInt(16).toByte() }.toByteArray()\n)\n'
    output += 'internal val nativePrefixScanConfigs = mapOf(\n' + ',\n'.join('    "' + name + '" to ' + block(json.dumps(config, ensure_ascii=False)) for name, config in configs.items()) + '\n)\n'
    output += 'internal val nativePrefixScanCases = ' + block('\n' + '\n'.join(rows) + '\n') + '.trim().lines()\n'
    fixture.write_text(output)
    report = {'upstream': LOCK, 'cases': len(rows), 'dictionary_backends': list(configs), 'scope': 'Observable skip distances, not C++ pointer views or reconstruction-state mechanics'}
    (ROOT / 'docs/prefix-scan-audit.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__': audit()
